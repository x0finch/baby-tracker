// Regenerates src/features/growth/who-data.ts from the CDC's copies of the WHO Child Growth
// Standards (LMS parameters by month, 0-24 months). The CDC files are US government works.
// Usage: node scripts/gen-who-growth.mjs
import { writeFileSync } from 'node:fs'

const BASE = 'https://ftp.cdc.gov/pub/Health_Statistics/NCHS/growthcharts'
const FILES = {
  weight: {
    male: 'WHO-Boys-Weight-for-age-Percentiles',
    female: 'WHO-Girls-Weight-for-age%20Percentiles',
  },
  length: {
    male: 'WHO-Boys-Length-for-age-Percentiles',
    female: 'WHO-Girls-Length-for-age-Percentiles',
  },
  head: {
    male: 'WHO-Boys-Head-Circumference-for-age-Percentiles',
    female: 'WHO-Girls-Head-Circumference-for-age-Percentiles',
  },
}

async function lms(file) {
  const res = await fetch(`${BASE}/${file}.csv`)
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`)
  const rows = (await res.text()).trim().split(/\r?\n/).slice(1)
  return rows.map((row, month) => {
    const [m, l, mid, s] = row.split(',').map(Number)
    if (m !== month) throw new Error(`${file}: unexpected month ${m} at row ${month}`)
    return [l, mid, s]
  })
}

const data = Object.fromEntries(
  await Promise.all(
    Object.entries(FILES).map(async ([measure, bySex]) => [
      measure,
      Object.fromEntries(
        await Promise.all(Object.entries(bySex).map(async ([sex, file]) => [sex, await lms(file)])),
      ),
    ]),
  ),
)

const body = Object.entries(data)
  .map(([measure, bySex]) => {
    const sexes = Object.entries(bySex)
      .map(
        ([sex, rows]) =>
          `    ${sex}: [\n${rows.map((r) => `      [${r.join(', ')}],`).join('\n')}\n    ],`,
      )
      .join('\n')
    return `  ${measure}: {\n${sexes}\n  },`
  })
  .join('\n')

writeFileSync(
  new URL('../src/features/growth/who-data.ts', import.meta.url),
  `// Generated by scripts/gen-who-growth.mjs; do not edit.
// WHO Child Growth Standards, LMS parameters [L, M, S] for months 0-24, as published by the
// CDC (https://www.cdc.gov/growthcharts/who-data-files.htm).

export const WHO_LMS = {
${body}
} as const satisfies Record<string, Record<'male' | 'female', readonly (readonly number[])[]>>
`,
)
